"""Run every eval and write one consolidated report.

WHY A SINGLE REPORT
-------------------
The two evals measure genuinely different things, so they stay separate
scripts. But they were producing two files that had to be read together and
could silently disagree with each other about the conditions they ran under -
one generated at prompt version v4, the other at v6, with nothing in either
saying so.

A report is a record of a run. If two records describe different runs, reading
them side by side is misleading rather than informative. This runs both against
the same code, in one pass, and writes one document stamped with the exact
model, prompt version and decoding settings that produced every number in it.

Usage:
    python evals/run_all.py
    python evals/run_all.py --no-cache     # ignore cached model responses
"""

import argparse
import asyncio
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "api"))
sys.path.insert(0, str(REPO_ROOT / "evals"))

import run_eval  # noqa: E402
import run_scenario_eval  # noqa: E402

from app.config import settings  # noqa: E402
from app.llm.prompts import PROMPT_VERSION  # noqa: E402

REPORT_PATH = REPO_ROOT / "evals" / "REPORT.md"


def _git_commit() -> str:
    """The commit the numbers came from, marked `-dirty` if they did not.

    A bare HEAD hash claims the run used exactly that commit's code. With
    uncommitted edits it did not: the M14 report was stamped `2da3dd6` while
    measuring M14 changes that only existed in the working tree.

    REPORT.md itself is excluded, because this script rewrites it - otherwise
    the second run on a clean commit would always call itself dirty.
    """
    try:
        head = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=REPO_ROOT, capture_output=True, text=True, check=True,
        ).stdout.strip()
        changes = subprocess.run(
            ["git", "status", "--porcelain", "--", ".", ":(exclude)evals/REPORT.md"],
            cwd=REPO_ROOT, capture_output=True, text=True, check=True,
        ).stdout.strip()
        return f"{head}-dirty" if changes else head
    except Exception:
        return "unknown"


def _cache_note(seconds: float) -> str:
    """Say so when a run was served from cache.

    A report showing "0s" invites the reader to think this eval is free. It is
    not - a cold run is several minutes of local inference. It is only instant
    because every response was already cached under an identical model,
    messages, schema and decoding configuration.
    """
    if seconds < 20:
        return " (served from cache; a cold run takes several minutes)"
    return ""


# What each held-out batch has been exposed to, stated beside its number. A
# held-out score is only as clean as its history, and the history is the point.
HELDOUT_NOTES = {
    "1": "read while diagnosing M14 failures - no longer clean",
    "2": "written before running; one case read while diagnosing",
}


def build(classification: dict, scenario: dict, seconds: float,
          heldout: dict[str, dict] | None = None) -> str:
    heldout = heldout or {}
    rank = classification.get("ranking") or {}

    lines = [
        "# Evaluation report",
        "",
        "Generated by `python evals/run_all.py`. Every number below comes from",
        "one run against the code and settings stated here.",
        "",
        "| | |",
        "|---|---|",
        f"| Model | `{settings.model}` |",
        f"| Ollama | `{scenario.get('ollama_version')}` |",
        f"| Prompt version | `{PROMPT_VERSION}` |",
        f"| Decoding | num_ctx {settings.num_ctx}, num_predict {settings.num_predict},"
        f" temperature {settings.temperature}, KV cache {settings.kv_cache_type} |",
        f"| Analysis batch size | {settings.analyze_batch_size} |",
        f"| Commit | `{_git_commit()}` |",
        f"| Generated | {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC |",
        f"| Total wall time | {seconds:.0f}s{_cache_note(seconds)} |",
        "",
        "The golden set is a 39-clause synthetic IRDAI-style policy authored for",
        "this repository, so the labels and the document come from one source and",
        "cannot drift apart. No real insurer wording is used.",
        "",
        "---",
        "",
        "## Headline",
        "",
        "| What is measured | Score | Kind |",
        "|---|---:|---|",
        f"| Clause classification (macro-F1) | **{classification['macro_f1']:.3f}** "
        "| quality |",
    ]
    if rank:
        lines.append(
            f"| Risk ranking expectations | **{rank['passed']}/{rank['total']}** | quality |"
        )
    lines += [
        f"| Scenario verdict accuracy | **{scenario['verdict_accuracy']:.3f}** | quality |",
    ]
    for batch, res in heldout.items():
        lines.append(
            f"| Scenario verdict accuracy, held-out batch {batch} ({res['total']} cases, "
            f"{HELDOUT_NOTES.get(batch, 'never tuned on')}) | **{res['verdict_accuracy']:.3f}** "
            f"| quality |"
        )
    lines += [
        f"| Scenario citation recall | **{scenario['citation_recall']:.3f}** | quality |",
        f"| Scenario false citation rate | "
        f"**{scenario['false_citation_rate']:.3f}** | quality |",
        f"| Quote fabrication rate | **{scenario['fabrication_rate']:.3f}** | quality |",
        f"| **Citation detection integrity** | "
        f"**{scenario['detection_integrity']:.3f}** | **guarantee** |",
        "",
        "### Only one of these is a promise",
        "",
        "Every row marked *quality* is a measure of how well a 7B model running on",
        "a laptop performs a hard task. Those numbers are published as they came",
        "out, including the ones that are not good.",
        "",
        "**Detection integrity is different in kind.** It asks: of the quotations",
        "the model invented, how many were caught and shown to the reader as",
        "unverified rather than presented as evidence? That is the property the",
        "grounding design actually promises, and it is the only number here that",
        "would count as a bug if it moved.",
        "",
        "It is computed by re-verifying every quotation independently and comparing",
        "against the flag the pipeline set - never by reading that flag. A",
        "self-reported guarantee is not a measurement: a broken verifier would",
        "cheerfully report a clean run.",
        "",
        "---",
        "",
        "## 1. Clause classification",
        "",
        f"**Macro-F1 {classification['macro_f1']:.3f}** · "
        f"accuracy {classification['accuracy']:.3f} · "
        f"{classification['clauses_analysed']}/{classification['clauses_expected']} clauses",
        "",
        "Macro-F1 rather than accuracy, because the golden policy has 8 exclusions",
        "and only 4 waiting periods. Accuracy lets a model coast on the common",
        "types; macro-F1 weights each equally, which matches reality - a missed",
        "waiting period misleads a policyholder just as badly as a missed exclusion.",
        "",
        "| Clause type | Support | Precision | Recall | F1 |",
        "|---|---:|---:|---:|---:|",
    ]
    for clause_type, m in classification["per_type"].items():
        if m["support"]:
            lines.append(
                f"| `{clause_type}` | {m['support']} | {m['precision']:.2f} "
                f"| {m['recall']:.2f} | {m['f1']:.2f} |"
            )

    if classification["confusions"]:
        lines += ["", "**Confusions** (expected → predicted):", ""]
        for (expected, predicted), n in classification["confusions"].most_common():
            lines.append(f"- `{expected}` → `{predicted}` ×{n}")

    # --- ranking ---
    if rank:
        lines += [
            "",
            "---",
            "",
            "## 2. Risk ranking",
            "",
            f"**{rank['passed']}/{rank['total']} expectations met** (top {rank['top_n']})",
            "",
            "Classification F1 measures labelling. This measures the ranking, which",
            "is the actual product. The two are not the same: an early version",
            "scored a perfect 1.000 on labels while burying the room-rent cap at",
            "position 14 and the senior co-payment at 22 - the two most common",
            "causes of an unexpected shortfall in an Indian health claim.",
            "",
            "Expectations are hand-authored in `golden/ranking-expectations.json`",
            "from how claims actually go wrong, and written before any ranking was",
            "inspected, so the metric tests the system rather than rationalising it.",
            "",
        ]
        if rank["misses"]:
            lines += ["**Should be in the top 10 but is not:**", ""]
            for m in rank["misses"]:
                lines.append(f"- `{m['number']}` (rank {m['rank'] or '—'}) — {m['reason']}")
            lines.append("")
        if rank["violations"]:
            lines += ["**In the top 10 but should not be:**", ""]
            for v in rank["violations"]:
                lines.append(f"- `{v['number']}` (rank {v['rank']}) — {v['reason']}")
            lines.append("")

    # --- scenarios ---
    lines += [
        "---",
        "",
        "## 3. Scenario simulator",
        "",
        f"**Verdict accuracy {scenario['verdict_accuracy']:.3f}** "
        f"({sum(r['verdict_ok'] for r in scenario['rows'])}/{scenario['total']}) · "
        f"citation recall {scenario['citation_recall']:.3f} · "
        f"detection integrity {scenario['detection_integrity']:.3f}",
        "",
        "| Case | Expected | Got | Cited | Quotes verified |",
        "|---|---|---|---|---|",
    ]
    for row in scenario["rows"]:
        mark = "" if row["verdict_ok"] else " ⚠"
        cite = ", ".join(row["cited"]) or "—"
        if row["required"] and not row["citation_ok"]:
            cite += f" (missing {', '.join(row['required'])})"
        lines.append(
            f"| `{row['id']}` | {row['expected']} | {row['got']}{mark} | {cite} "
            f"| {'yes' if row['grounded'] else '**flagged**'} |"
        )

    misses = [r for r in scenario["rows"] if not r["verdict_ok"]]
    if misses:
        lines += [
            "",
            "### What the misses actually need",
            "",
            "These are not random. Read them together:",
            "",
        ]
        for row in misses:
            lines.append(
                f"- **`{row['id']}`** — expected `{row['expected']}`, got "
                f"`{row['got']}`. {row['why']}"
            )
        lines += [
            "",
            "Most require either date arithmetic (is 5 years more than 36 months?)",
            "or following an exception inside a clause (\"unless necessitated by an",
            "Accident\"). That is multi-hop reasoning over interacting rules, which",
            "is where a 7B model is weakest.",
            "",
            "Single-clause classification scores macro-F1 "
            f"{classification['macro_f1']:.3f}. Combining three interacting rules",
            f"scores {scenario['verdict_accuracy']:.3f}. **The gap between those two",
            "numbers is the finding**, and it is the case for measuring a hosted",
            "frontier model on this same set before assuming a bigger model is or",
            "is not worth it.",
        ]

    if heldout:
        lines += [
            "",
            "---",
            "",
            "## 3b. Held-out scenarios",
            "",
            "The main 40 cases have been used to make many keep-or-revert decisions, and",
            "the reasoning prompt contains one of them as its example. A score on cases",
            "you tuned against measures how well the system fits them. These batches",
            "were written separately and are run only to measure, so the gap between",
            "their score and the main set's is an estimate of how much of the main",
            "score is fit rather than skill. Single run each; see the learning log for",
            "the majority-of-three figures.",
            "",
        ]
        for batch, res in heldout.items():
            lines.append(
                f"**Batch {batch}** ({HELDOUT_NOTES.get(batch, 'never tuned on')}): "
                f"verdict accuracy {res['verdict_accuracy']:.3f} "
                f"({sum(r['verdict_ok'] for r in res['rows'])}/{res['total']}), "
                f"citation recall {res['citation_recall']:.3f}, "
                f"detection integrity {res['detection_integrity']:.3f}"
            )
            for row in res["rows"]:
                if not row["verdict_ok"]:
                    lines.append(f"- `{row['id']}`: expected `{row['expected']}`, got `{row['got']}`")
            lines.append("")

    lines += [
        "",
        "---",
        "",
        "## Reproducing this",
        "",
        "```bash",
        "ollama pull qwen2.5:7b-instruct-q4_K_M",
        "cd api && python -m venv .venv",
        ".venv/Scripts/python.exe -m pip install -r requirements.txt",
        "cd .. && python evals/run_all.py",
        "```",
        "",
        "The golden PDF is generated, not committed, so it is rebuilt from",
        "`evals/golden/build_synthetic_policy.py` if missing. Model responses are",
        "cached by a hash of model, messages, schema, decoding settings and the",
        "server's KV cache precision, so a second run costs seconds - and",
        "changing any of those recomputes rather",
        "than serving a stale answer. The prompt version is a label, not part of",
        "the key: an unchanged prompt replays its stored answer even after the",
        "version is bumped, so only the cases a change reached are regenerated.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--no-cache", action="store_true")
    args = parser.parse_args()
    use_cache = not args.no_cache

    started = time.perf_counter()

    print("=" * 60)
    print("1/2  clause classification + ranking")
    print("=" * 60)
    classification = asyncio.run(run_eval.run(use_cache=use_cache))

    print()
    print("=" * 60)
    print("2/2  scenario simulator")
    print("=" * 60)
    scenario = asyncio.run(run_scenario_eval.run(use_cache=use_cache))
    # Recorded like any other scenario run, so a full report run counts toward
    # the history that comparisons and stability are computed from.
    comparison = run_scenario_eval.render_comparison(
        run_scenario_eval.compare_with_previous(
            scenario, run_scenario_eval.load_history()
        )
    )
    run_scenario_eval.record_run(scenario)

    # Held-out batches: measured, never recorded into the history the main
    # set's comparisons and watchlist are computed from.
    heldout = {
        batch: asyncio.run(run_scenario_eval.run(use_cache=use_cache, cases_path=path))
        for batch, path in run_scenario_eval.HELDOUT_PATHS.items()
    }

    seconds = time.perf_counter() - started
    REPORT_PATH.write_text(build(classification, scenario, seconds, heldout), encoding="utf-8")

    print()
    print("=" * 60)
    print(f"  classification macro-F1 : {classification['macro_f1']:.3f}")
    rank = classification.get("ranking") or {}
    if rank:
        print(f"  ranking expectations    : {rank['passed']}/{rank['total']}")
    print(f"  scenario verdict acc.   : {scenario['verdict_accuracy']:.3f}")
    for batch, res in heldout.items():
        print(f"  held-out batch {batch}      : {res['verdict_accuracy']:.3f}")
    print(f"  citation recall         : {scenario['citation_recall']:.3f}")
    print(f"  fabrication rate        : {scenario['fabrication_rate']:.3f}")
    print(f"  DETECTION INTEGRITY     : {scenario['detection_integrity']:.3f}  "
          f"{'OK' if scenario['detection_integrity'] >= 1.0 else 'FAILED - guarantee broken'}")
    print("=" * 60)
    print(f"wrote {REPORT_PATH.relative_to(REPO_ROOT)} in {seconds:.0f}s")
    print()
    print(comparison)

    # A non-zero exit if the guarantee is broken, so this can gate a pipeline.
    # The quality numbers deliberately do NOT gate: they are allowed to be poor,
    # and a threshold on them would only invite tuning to the threshold.
    if any(r["detection_integrity"] < 1.0 for r in [scenario, *heldout.values()]):
        sys.exit(1)


if __name__ == "__main__":
    main()
